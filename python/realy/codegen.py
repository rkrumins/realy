"""Generate ClickHouse DDL from the contracts (feature schema -> typed feature columns).

    python -m realy.codegen        # writes contracts/storage/clickhouse/*.sql

ClickHouse ingests asynchronously from Kafka (Kafka table engine, ProtobufSingle with the contract
.proto files mounted as format schemas) -> materialized views -> ReplacingMergeTree tables. The hot
path never waits on ClickHouse; it only waits for the Kafka acks=all write (the audit WAL).
"""
from __future__ import annotations

from pathlib import Path

from .features import load_schema
from .scenario import REPO_ROOT

OUT = REPO_ROOT / "contracts" / "storage" / "clickhouse"
HEADER = "-- GENERATED by `python -m realy.codegen` from contracts/ — do not edit by hand.\n"
STAGES = {11: "queue_wait", 12: "deserialize", 20: "shuffle", 21: "state_features", 22: "feature_store_write",
          30: "feature_lookup", 31: "feature_assemble", 40: "model_call", 41: "model_batch_wait",
          42: "model_server_queue", 43: "model_server_compute", 50: "rules", 51: "policy", 60: "audit_ack", 61: "sink",
          81: "async_wait"}
ENUM = {
    "outcome": ["OUTCOME_UNSPECIFIED", "APPROVE", "REVIEW", "DECLINE"],
    "path": ["FULL", "RULES_ONLY_FALLBACK", "PROVISIONAL", "FINAL_AFTER_PROVISIONAL", "ECHO"],
    "ingress": ["UNSPECIFIED", "SYNC_GRPC", "SYNC_HTTP", "ASYNC_KAFKA_GATEWAY", "ASYNC_FLINK_INLINE"],
    "payment_type": ["UNSPECIFIED", "CARD_PURCHASE", "ATM_WITHDRAWAL", "TRANSFER", "CARD_REFUND"],
    "channel": ["UNSPECIFIED", "POS", "ECOM", "ATM", "MOTO", "IN_APP", "ONLINE_BANKING"],
    "entry_mode": ["UNSPECIFIED", "CHIP", "CONTACTLESS", "MAGSTRIPE", "MANUAL", "WALLET_TOKEN", "ECOM_3DS",
                   "ECOM_NON_3DS", "CREDENTIAL_ON_FILE", "BANK_APP"],
    "fraud_type": ["NONE", "CARD_TESTING", "ACCOUNT_TAKEOVER", "LOST_STOLEN", "COUNTERFEIT", "MERCHANT_BREACH",
                   "ATM_CASHOUT", "APP_SCAM_MULE", "BUST_OUT", "BOT_ECOM", "FRIENDLY_FRAUD"],
}
EVENT_COLS = [  # (proto field, ClickHouse type)
    ("event_id", "UInt64"), ("event_time_us", "Int64"), ("payment_type", "Int8"), ("customer_id", "UInt64"),
    ("account_id", "UInt64"), ("card_id", "UInt64"), ("card_type", "Int8"), ("amount_minor", "Int64"),
    ("currency", "String"), ("amount_usd_minor", "Int64"), ("merchant_id", "UInt64"), ("mcc", "UInt32"),
    ("merchant_country", "String"), ("terminal_id", "UInt64"), ("channel", "Int8"), ("entry_mode", "Int8"),
    ("card_present", "UInt8"), ("lat", "Float64"), ("lon", "Float64"), ("device_id", "UInt64"), ("ip_v4", "UInt32"),
    ("ip_country", "String"), ("ip_asn", "UInt32"), ("payee_id", "UInt64"), ("cvv_match", "UInt8"),
    ("avs_match", "UInt8"), ("recurring", "UInt8"), ("credit_limit_usd", "UInt32"),
]
KAFKA = "SETTINGS kafka_broker_list = '__KAFKA_BROKERS__', kafka_topic_list = '{topic}', kafka_group_name = '{group}',\n" \
        "         kafka_format = 'ProtobufSingle', kafka_schema = '{schema}', kafka_num_consumers = {consumers},\n" \
        "         kafka_flush_interval_ms = 1000, kafka_max_block_size = 65536, kafka_thread_per_consumer = 1,\n" \
        "         kafka_handle_error_mode = 'stream'"


def _enum(name: str, col: str) -> str:
    arr = ", ".join(f"'{v}'" for v in ENUM[name])
    return f"arrayElement([{arr}], toInt32({col}) + 1)"


def generate(consumers: int = 2) -> dict[str, str]:
    schema = load_schema()
    files: dict[str, str] = {}
    files["01_database.sql"] = HEADER + "CREATE DATABASE IF NOT EXISTS realy;\n"

    # ------------------------------------------------------------------ events_raw
    ev_q = ",\n  ".join(f"`{c}` {t}" for c, t in EVENT_COLS)
    ev_t = ",\n  ".join(f"`{c}` {'LowCardinality(String)' if c in ('payment_type', 'channel', 'entry_mode', 'card_type') else t}"
                        for c, t in EVENT_COLS)
    ev_sel = ",\n  ".join(
        (_enum(c, c) + f" AS `{c}`") if c in ("payment_type", "channel", "entry_mode") else
        (f"toString(card_type) AS `card_type`" if c == "card_type" else f"`{c}`") for c, _ in EVENT_COLS)
    files["02_events.sql"] = HEADER + f"""
CREATE TABLE IF NOT EXISTS realy.events_queue (
  {ev_q}
) ENGINE = Kafka
{KAFKA.format(topic='payments.events.raw', group='clickhouse-events', schema='realy/payments/v1/transaction.proto:TransactionEvent', consumers=consumers)};

CREATE TABLE IF NOT EXISTS realy.events_raw (
  run_id LowCardinality(String),
  {ev_t},
  event_time DateTime64(6) MATERIALIZED fromUnixTimestamp64Micro(event_time_us),
  ingested_at DateTime64(6) DEFAULT now64(6)
) ENGINE = ReplacingMergeTree(ingested_at)
PARTITION BY toYYYYMMDD(fromUnixTimestamp64Micro(event_time_us))
ORDER BY (customer_id, run_id, event_id)
TTL toDateTime(ingested_at) + INTERVAL 30 DAY;

CREATE MATERIALIZED VIEW IF NOT EXISTS realy.events_mv TO realy.events_raw AS
SELECT
  arrayElement(_headers.value, indexOf(_headers.name, 'x-run-id')) AS run_id,
  {ev_sel}
FROM realy.events_queue WHERE length(_error) = 0;
"""

    # ------------------------------------------------------------------ decisions
    fcols = ",\n  ".join(f"`f_{f.name}` Float32" for f in schema.features)
    fsel = ",\n  ".join(f"`features.values`[{f.index + 1}] AS `f_{f.name}`" for f in schema.features)
    lat_cols = ",\n  ".join(f"`lat_{n}_us` Int32" for n in STAGES.values())
    lat_sel = ",\n  ".join(
        f"toInt32(arraySum(arrayFilter((d, s) -> s = {k}, `trace.spans.dur_us`, `trace.spans.stage`))) AS `lat_{n}_us`"
        for k, n in STAGES.items())
    dq_event = ",\n  ".join(f"`event.{c}` {t}" for c, t in EVENT_COLS if c != "event_id")
    files["03_decisions.sql"] = HEADER + f"""
-- Identity of a decision is (run_id, event_id): benchmark event ids are deterministic per world+seed and
-- repeat across runs (production: run_id is empty and event_id is globally unique).
-- Feature schema version {schema.version}: {len(schema.features)} features -> f_* columns (features_raw keeps the exact tensor).
CREATE TABLE IF NOT EXISTS realy.decisions_queue (
  `event_id` UInt64,
  `outcome` Int8,
  `score` Float32,
  `reason_codes` Array(String),
  `policy_version` String,
  `rule_set_version` String,
  `path` Int8,
  `degraded` UInt8,
  `ingress_mode` Int8,
  `instance_id` String,
  `decided_at_us` Int64,
  `revision` UInt32,
  `feature_schema_version` UInt32,
  {dq_event},
  `features.values` Array(Float32),
  `features.missing_bitmap` String,
  `model.model_name` String,
  `model.model_version` String,
  `model.score` Float32,
  `model.input_hash` UInt64,
  `model.timed_out` UInt8,
  `model.errored` UInt8,
  `model.batch_size` UInt32,
  `trace.run_id` String,
  `trace.gen_id` UInt32,
  `trace.seq` UInt64,
  `trace.t_intended_us` Int64,
  `trace.t_sent_us` Int64,
  `trace.spans.stage` Array(Int32),
  `trace.spans.start_us` Array(Int64),
  `trace.spans.dur_us` Array(Int32)
) ENGINE = Kafka
{KAFKA.format(topic='payments.decisions', group='clickhouse-decisions', schema='realy/scoring/v1/decision.proto:DecisionRecord', consumers=consumers)};

CREATE TABLE IF NOT EXISTS realy.decisions (
  event_id UInt64,
  revision UInt32,
  customer_id UInt64,
  card_id UInt64,
  merchant_id UInt64,
  payee_id UInt64,
  device_id UInt64,
  event_time DateTime64(6),
  decided_at DateTime64(6),
  payment_type LowCardinality(String),
  channel LowCardinality(String),
  entry_mode LowCardinality(String),
  mcc UInt32,
  merchant_country LowCardinality(String),
  amount_usd_minor Int64,
  outcome LowCardinality(String),
  score Float32,
  reason_codes Array(LowCardinality(String)),
  path LowCardinality(String),
  degraded UInt8,
  ingress_mode LowCardinality(String),
  instance_id LowCardinality(String),
  policy_version LowCardinality(String),
  rule_set_version LowCardinality(String),
  model_name LowCardinality(String),
  model_version LowCardinality(String),
  model_input_hash UInt64,
  model_timed_out UInt8,
  model_batch_size UInt32,
  feature_schema_version UInt16,
  features_raw Array(Float32),
  features_missing String,
  {fcols},
  run_id LowCardinality(String),
  gen_id UInt32,
  seq UInt64,
  t_intended_us Int64 CODEC(Delta, ZSTD),
  t_sent_us Int64 CODEC(Delta, ZSTD),
  {lat_cols},
  hot_path_us Int32,
  ingested_at DateTime64(6) DEFAULT now64(6)
) ENGINE = ReplacingMergeTree(ingested_at)
PARTITION BY toYYYYMMDD(event_time)
ORDER BY (customer_id, run_id, event_id, revision)
TTL toDateTime(ingested_at) + INTERVAL 400 DAY;

CREATE MATERIALIZED VIEW IF NOT EXISTS realy.decisions_mv TO realy.decisions AS
SELECT
  event_id, revision,
  `event.customer_id` AS customer_id, `event.card_id` AS card_id, `event.merchant_id` AS merchant_id,
  `event.payee_id` AS payee_id, `event.device_id` AS device_id,
  fromUnixTimestamp64Micro(`event.event_time_us`) AS event_time,
  fromUnixTimestamp64Micro(decided_at_us) AS decided_at,
  {_enum('payment_type', '`event.payment_type`')} AS payment_type,
  {_enum('channel', '`event.channel`')} AS channel,
  {_enum('entry_mode', '`event.entry_mode`')} AS entry_mode,
  `event.mcc` AS mcc, `event.merchant_country` AS merchant_country, `event.amount_usd_minor` AS amount_usd_minor,
  {_enum('outcome', 'outcome')} AS outcome, score, reason_codes,
  {_enum('path', 'path')} AS path, degraded,
  {_enum('ingress', 'ingress_mode')} AS ingress_mode, instance_id, policy_version, rule_set_version,
  `model.model_name` AS model_name, `model.model_version` AS model_version, `model.input_hash` AS model_input_hash,
  `model.timed_out` AS model_timed_out, `model.batch_size` AS model_batch_size,
  feature_schema_version, `features.values` AS features_raw, `features.missing_bitmap` AS features_missing,
  {fsel},
  `trace.run_id` AS run_id, `trace.gen_id` AS gen_id, `trace.seq` AS seq,
  `trace.t_intended_us` AS t_intended_us, `trace.t_sent_us` AS t_sent_us,
  {lat_sel},
  toInt32(arrayFirst((st, s) -> s = 70, `trace.spans.start_us`, `trace.spans.stage`)
          - arrayFirst((st, s) -> s = 10, `trace.spans.start_us`, `trace.spans.stage`)) AS hot_path_us
FROM realy.decisions_queue WHERE length(_error) = 0;
"""

    # ------------------------------------------------------------------ labels
    files["04_labels.sql"] = HEADER + f"""
CREATE TABLE IF NOT EXISTS realy.labels_queue (
  event_id UInt64, label_time_us Int64, event_time_us Int64, is_fraud UInt8, fraud_type Int8,
  campaign_id UInt64, source Int8, customer_id UInt64, card_id UInt64, amount_usd_minor Int64
) ENGINE = Kafka
{KAFKA.format(topic='payments.labels', group='clickhouse-labels', schema='realy/payments/v1/label.proto:FraudLabel', consumers=1)};

CREATE TABLE IF NOT EXISTS realy.labels (
  run_id LowCardinality(String), event_id UInt64, label_time DateTime64(6), event_time DateTime64(6), is_fraud UInt8,
  fraud_type LowCardinality(String), campaign_id UInt64, source Int8, customer_id UInt64, card_id UInt64,
  amount_usd_minor Int64, ingested_at DateTime64(6) DEFAULT now64(6)
) ENGINE = ReplacingMergeTree(ingested_at) ORDER BY (run_id, event_id);

CREATE MATERIALIZED VIEW IF NOT EXISTS realy.labels_mv TO realy.labels AS
SELECT arrayElement(_headers.value, indexOf(_headers.name, 'x-run-id')) AS run_id,
       event_id, fromUnixTimestamp64Micro(label_time_us) AS label_time, fromUnixTimestamp64Micro(event_time_us) AS event_time,
       is_fraud, {_enum('fraud_type', 'fraud_type')} AS fraud_type, campaign_id, source, customer_id, card_id, amount_usd_minor
FROM realy.labels_queue WHERE length(_error) = 0;
"""

    # ------------------------------------------------------------------ views
    fnames = ", ".join(f"d.f_{f.name}" for f in schema.features)
    files["05_views.sql"] = HEADER + f"""
-- Point-in-time correct training set: features exactly as served at decision time + delayed labels.
CREATE OR REPLACE VIEW realy.v_training_dataset AS
SELECT d.run_id, d.event_id, d.event_time, d.customer_id, d.card_id, d.amount_usd_minor, d.payment_type, d.channel,
       d.outcome, d.score, d.model_version, d.feature_schema_version, {fnames},
       ifNull(l.is_fraud, 0) AS label_is_fraud, ifNull(l.fraud_type, 'NONE') AS label_fraud_type, l.label_time
FROM (SELECT * FROM realy.decisions FINAL WHERE revision = 0) AS d
LEFT JOIN (SELECT * FROM realy.labels FINAL) AS l ON l.run_id = d.run_id AND l.event_id = d.event_id;

-- Audit completeness: transactions that never received a decision.
CREATE OR REPLACE VIEW realy.v_audit_gaps AS
SELECT e.run_id, e.event_id, e.customer_id, e.event_time_us, e.ingested_at
FROM realy.events_raw AS e
LEFT ANTI JOIN (SELECT DISTINCT run_id, event_id FROM realy.decisions) AS d ON d.run_id = e.run_id AND d.event_id = e.event_id;

-- Per-second latency/throughput from the audit log (independent second measurement).
CREATE OR REPLACE VIEW realy.v_latency_by_second AS
SELECT run_id, toStartOfSecond(decided_at) AS second, count() AS decisions,
       quantileExact(0.5)(hot_path_us) / 1000 AS hot_p50_ms, quantileExact(0.99)(hot_path_us) / 1000 AS hot_p99_ms,
       quantileExact(0.99)(lat_feature_lookup_us) / 1000 AS feature_p99_ms, quantileExact(0.99)(lat_model_call_us) / 1000 AS model_p99_ms,
       quantileExact(0.99)(dateDiff('microsecond', decided_at, ingested_at)) / 1000 AS audit_visibility_p99_ms,
       countIf(degraded = 1) AS degraded, countIf(outcome = 'DECLINE') AS declines
FROM realy.decisions GROUP BY run_id, second;
"""
    from .report.history import ddl as runs_ddl
    files["06_runs.sql"] = runs_ddl(HEADER)
    return files


def write(consumers: int = 2) -> list[Path]:
    OUT.mkdir(parents=True, exist_ok=True)
    out = []
    for name, sql in generate(consumers).items():
        p = OUT / name
        p.write_text(sql.lstrip("\n") if sql.startswith("\n") else sql)
        out.append(p)
    return out


if __name__ == "__main__":
    for p in write():
        print(p)
