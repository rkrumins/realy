"""Render the contract-derived Kubernetes manifests (python -m realy.k8s).

Kustomize may not read files outside its root, and these must never drift from contracts/, so they
are generated:
  base/generated                   ClickHouse DDL ConfigMap (contracts/storage/clickhouse) and the .proto
                                   format-schema ConfigMap + volume patch ClickHouse's Kafka engine needs
  components/operators/generated   Strimzi KafkaTopic CRs (contracts/kafka/topics.yaml)
  components/standalone/generated  the topic-creation script ConfigMap (deploy/compose/kafka/create-topics.sh)
"""
from __future__ import annotations

from pathlib import Path

import yaml

from .scenario import REPO_ROOT

K8S = REPO_ROOT / "deploy" / "k8s"
OUT = K8S / "base" / "generated"
HEADER = "# GENERATED by `python -m realy.k8s` from contracts/ - do not edit.\n"


def _dump(docs: list[dict]) -> str:
    return HEADER + "---\n".join(yaml.safe_dump(d, sort_keys=False) for d in docs)


def topics() -> str:
    spec = yaml.safe_load((REPO_ROOT / "contracts" / "kafka" / "topics.yaml").read_text())
    docs = []
    for name, t in spec["topics"].items():
        cfg = {str(k): str(v) for k, v in (t.get("config") or {}).items()}
        if "retention_ms" in t:
            cfg["retention.ms"] = str(t["retention_ms"])
        cfg["min.insync.replicas"] = str(spec["defaults"]["min_insync_replicas"])
        docs.append({"apiVersion": "kafka.strimzi.io/v1beta2", "kind": "KafkaTopic",
                     "metadata": {"name": name.replace(".", "-"), "labels": {"strimzi.io/cluster": "realy"}},
                     "spec": {"topicName": name, "partitions": int(t["partitions"]),
                              "replicas": int(spec["defaults"]["replication_factor"]), "config": cfg}})
    return _dump(docs)


def clickhouse_ddl() -> str:
    d = REPO_ROOT / "contracts" / "storage" / "clickhouse"
    data = {p.name: p.read_text() for p in sorted(d.glob("*.sql"))}
    return _dump([{"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "clickhouse-ddl"}, "data": data}])


def protos() -> str:
    root = REPO_ROOT / "contracts" / "proto"
    data = {str(p.relative_to(root)).replace("/", "__"): p.read_text() for p in sorted(root.rglob("*.proto"))}
    return _dump([{"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "contract-protos"}, "data": data}])


def protos_volume_patch() -> str:
    """Strategic-merge patch restoring the proto directory layout inside the ClickHouse pod."""
    root = REPO_ROOT / "contracts" / "proto"
    items = [{"key": str(p.relative_to(root)).replace("/", "__"), "path": str(p.relative_to(root))}
             for p in sorted(root.rglob("*.proto"))]
    return _dump([{"apiVersion": "apps/v1", "kind": "StatefulSet", "metadata": {"name": "clickhouse"},
                   "spec": {"template": {"spec": {"volumes": [
                       {"name": "protos", "configMap": {"name": "contract-protos", "items": items}}]}}}}])


def topics_script() -> str:
    script = (REPO_ROOT / "deploy" / "compose" / "kafka" / "create-topics.sh").read_text()
    return _dump([{"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "kafka-topics-script"},
                   "data": {"create-topics.sh": script}}])


def write() -> list[Path]:
    files = {OUT / "clickhouse-ddl.yaml": clickhouse_ddl(), OUT / "contract-protos.yaml": protos(),
             OUT / "clickhouse-protos-volume.patch.yaml": protos_volume_patch(),
             K8S / "components" / "operators" / "generated" / "kafka-topics.yaml": topics(),
             K8S / "components" / "standalone" / "generated" / "kafka-topics-script.yaml": topics_script()}
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return list(files)


if __name__ == "__main__":
    for p in write():
        print(p)
