def _cell(s: Any) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def _table(head: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def _code(s: Any) -> str:
    s = str(s)
    return f"`{s}`" if s else ""


# ------------------------------------------------------------------------------------------ scenario
SCENARIO_MODELS = ["Scenario", "WorldSpec", "TrafficSpec", "RateProfile", "FraudSpec", "CampaignSpec",
                   "SyncSpec", "BudgetSpec", "GuardrailSpec"]
SECTION_KEY = {"WorldSpec": "world", "TrafficSpec": "traffic", "RateProfile": "traffic.profile",
               "FraudSpec": "fraud", "CampaignSpec": "fraud.campaigns[]", "SyncSpec": "sync",
               "BudgetSpec": "budget", "GuardrailSpec": "guardrails"}


def _source_fields(cls: type) -> dict[str, tuple[str, str, str]]:
    """field -> (type text, default text, comment) straight from the class source."""
    out: dict[str, tuple[str, str, str]] = {}
    pending: list[str] = []
    for line in inspect.getsource(cls).splitlines()[1:]:
        if re.match(r"^    #\s?", line):
            pending.append(re.sub(r"^    #\s?", "", line))
            continue
        m = re.match(r"^    ([a-z_][a-z0-9_]*): (.+?)(?:\s+#\s*(.*))?$", line)
        if m and not line.strip().startswith(("def ", "@")):
            typ, _, default = m.group(2).partition(" = ")
            comment = " ".join(pending + ([m.group(3)] if m.group(3) else []))
            out[m.group(1)] = (typ.strip(), default.strip(), comment)
        pending = [] if not line.startswith("    #") else pending
    return out


def _default_text(field: Any, src_default: str) -> str:
    if field.default_factory is not None:
        try:
            v = field.default_factory()
        except TypeError:
            return ""
        if hasattr(v, "model_dump"):
            return "(object)"
        txt = json.dumps(v)
        return txt if len(txt) <= 90 else "see below"
    if src_default.startswith("Field("):
        return ""
    return src_default


def scenario_schema() -> str:
    parts = [HEADER.format(src="python/realy/scenario.py"), "# Scenario schema\n\n",
             "A scenario is one YAML file in `scenarios/` (or saved from the console's builder) that fully "
             "describes a reproducible run. Unknown keys are rejected. The JSON Schema is served at "
             "`GET /api/reference/scenario-schema`; the console builder validates against it.\n\n",
             "`scoring:` and `model_server:` are proto3-JSON documents of `ScoringConfig` / `ModelServerConfig` "
             "- see [config.md](config.md). Fields left out take the defaults listed there.\n\n"]
    for name in SCENARIO_MODELS:
        cls = getattr(scenario_mod, name)
        src = _source_fields(cls)
        key = SECTION_KEY.get(name, "(top level)")
        doc = (cls.__doc__ or "").strip()
        parts.append(f"## `{key}` - {name}\n\n")
        if doc and not doc.startswith(("Usage docs", "!!! abstract")):
            parts.append(doc + "\n\n")
        rows = []
        for fname, field in cls.model_fields.items():
            typ, sdef, comment = src.get(fname, ("", "", ""))
            rows.append([_code(fname), _code(typ), _code(_default_text(field, sdef)), comment])
        parts.append(_table(["Field", "Type", "Default", "Description"], rows) + "\n")
        if name == "FraudSpec":
            parts.append("Default `mix`: " + ", ".join(f"`{k}` {v:g}" for k, v in
                                                       cls.model_fields["mix"].default_factory().items()) + "\n\n")
    parts.append("## Fraud typologies\n\n`" + "`, `".join(scenario_mod.fraud_kinds()) + "` - described in "
                 "[synthetic-data.md](../synthetic-data.md).\n")
    return "".join(parts)


# ------------------------------------------------------------------------------------------ config
_FIELD = re.compile(r"^\s*(repeated\s+)?(map<[^>]+>|[\w.]+)\s+(\w+)\s*=\s*(\d+)\s*;\s*(?://\s*(.*))?$")
_ENUMV = re.compile(r"^\s*(\w+)\s*=\s*(\d+)\s*;\s*(?://\s*(.*))?$")


def _parse_proto(text: str) -> list[dict[str, Any]]:
    """Messages / enums of one .proto file with their leading and trailing `//` comments, in order.
    `// ---- title ----` lines become section headings. Handles one-line messages and oneofs."""
    blocks: list[dict[str, Any]] = []
    comments: list[str] = []
    cur: dict[str, Any] | None = None
    oneof: str | None = None

    def add_item(line: str) -> None:
        assert cur is not None
        m = _FIELD.match(line) if cur["kind"] == "message" else _ENUMV.match(line)
        if not m:
            return
        if cur["kind"] == "message":
            cur["items"].append({"name": m.group(3), "type": (m.group(1) or "") + m.group(2), "num": int(m.group(4)),
                                 "doc": " ".join(comments + ([m.group(5)] if m.group(5) else [])), "oneof": oneof})
        else:
            cur["items"].append({"name": m.group(1), "num": int(m.group(2)),
                                 "doc": " ".join(comments + ([m.group(3)] if m.group(3) else []))})

    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("//"):
            c = line[2:].strip()
            if c.startswith("----"):
                blocks.append({"kind": "section", "name": c.strip("- ").strip()})
                comments = []
            else:
                comments.append(c)
            continue
        if cur is not None and cur["kind"] == "service":
            m = re.match(r"^rpc\s+(\w+)\s*\(\s*(stream\s+)?([\w.]+)\s*\)\s*returns\s*\(\s*(stream\s+)?([\w.]+)\s*\)", line)
            if m:
                cur["items"].append({"name": m.group(1), "request": ("stream " if m.group(2) else "") + m.group(3),
                                     "response": ("stream " if m.group(4) else "") + m.group(5), "doc": " ".join(comments)})
            elif line == "}":
                blocks.append(cur)
                cur = None
            comments = []
            continue
        if cur is None:
            ms = re.match(r"^service\s+(\w+)\s*\{", line)
            if ms:
                cur = {"kind": "service", "name": ms.group(1), "doc": " ".join(comments), "items": []}
                comments = []
                continue
            m = re.match(r"^(message|enum)\s+(\w+)\s*\{(.*)$", line)
            if not m:
                comments = []          # file header, syntax/package/option lines
                continue
            cur = {"kind": m.group(1), "name": m.group(2), "doc": " ".join(comments), "items": []}
            comments = []
            rest = m.group(3).strip()
            if rest.endswith("}"):     # one-line message
                for part in filter(None, (x.strip() for x in rest[:-1].split(";"))):
                    add_item(part + ";")
                blocks.append(cur)
                cur = None
            continue
        if line.startswith("oneof "):
            oneof = re.match(r"oneof\s+(\w+)", line).group(1)
        elif line == "}":
            if oneof:
                oneof = None
            else:
                blocks.append(cur)
                cur = None
        elif line:
            add_item(line)
        comments = []
    return blocks


def config() -> str:
    path = REPO_ROOT / "contracts" / "proto" / "realy" / "bench" / "v1" / "control.proto"
    blocks = _parse_proto(path.read_text())
    defaults = {"ScoringConfig": SCORING_DEFAULTS, "ModelServerConfig": MODEL_SERVER_DEFAULTS}
    parts = [HEADER.format(src="contracts/proto/realy/bench/v1/control.proto"), "# Runtime configuration\n\n",
             "Runtime knobs of the Java services, as proto3 JSON (snake_case keys). The same document is used in "
             "a scenario's `scoring:` / `model_server:` sections, on the services' admin HTTP endpoints "
             "(`POST /admin/config`) and on the compacted `bench.control` topic, so changes made live from the "
             "console's control drawer use exactly this schema.\n\n",
             "Every run sends a complete config: fields a scenario leaves out are filled from the defaults below, "
             "so nothing leaks from one run into the next.\n\n"]
    for b in blocks:
        if b["kind"] == "section":
            parts.append(f"## {b['name'][:1].upper() + b['name'][1:]}\n\n")
            continue
        parts.append(f"### `{b['name']}`" + (" (enum)" if b["kind"] == "enum" else "") + "\n\n")
        if b["doc"]:
            parts.append(b["doc"] + "\n\n")
        if not b["items"]:
            continue
        if b["kind"] == "enum":
            parts.append(_table(["Value", "Number", "Meaning"], [[_code(i["name"]), i["num"], i["doc"]] for i in b["items"]]))
        else:
            d = defaults.get(b["name"])
            head = ["Field", "Type", "#"] + (["Default"] if d else []) + ["Description"]
            rows = []
            for i in b["items"]:
                typ = _code(i["type"]) + (f" (oneof {i['oneof']})" if i.get("oneof") else "")
                row = [_code(i["name"]), typ, i["num"]]
                if d:
                    row.append(_code(json.dumps(d[i["name"]])) if i["name"] in d else "")
                rows.append(row + [i["doc"]])
            parts.append(_table(head, rows))
        parts.append("\n")
    parts.append("## Example\n\n```yaml\nscoring:\n  budget_ms: 100\n  feature_deadline_ms: 30\n  model_deadline_ms: 80\n"
                 "  on_deadline: FALLBACK_RULES\n  feature_lookup_delay: { uniform: { min_ms: 2, max_ms: 8 } }\n"
                 "model_server:\n  service_time: { uniform: { min_ms: 30, max_ms: 100 } }\n  workers: 8\n"
                 "  max_batch: 16\n  max_queue_delay_us: 2000\n```\n")
    return "".join(parts)


