def http_api() -> str:
    from .control.app import app

    spec = app.openapi()
    parts = [HEADER.format(src="python/realy/control (FastAPI OpenAPI)"), "# Console HTTP API\n\n",
             "The console UI is a client of this API; scripts and CI can use it too. Live OpenAPI: "
             "`/api/openapi.json`, interactive explorer: `/api/swagger`.\n\n",
             "**Auth.** When `REALY_CONSOLE_TOKEN` is set every `/api/*` route except `/api/health` and "
             "`/api/auth/*` needs `Authorization: Bearer <token>` or the session cookie set by "
             "`POST /api/auth/login`. See [security.md](../security.md).\n\n",
             "**Live telemetry.** WebSocket `/api/live` (session cookie, Bearer header or `?token=`) pushes JSON "
             "messages: `status` (run queue + current run, on connect and on change), `metrics` (1 s "
             "`MetricsSnapshot` per source: emitter, collector, gateway, model, flink), `log` (driver log lines) "
             "and `decision` (a rate-limited sample of decisions, ~20/s, for the live feed). History for a "
             "late joiner: `GET /api/live/history`. Unauthorised connections are closed with code 4401.\n\n"]
    by_tag: dict[str, list[list[Any]]] = {}
    for path, ops in spec.get("paths", {}).items():
        for method, op in ops.items():
            tag = (op.get("tags") or ["console"])[0]
            params = ", ".join(("" if p.get("required") else "?") + p["name"] for p in op.get("parameters", [])
                               if p.get("in") == "query")
            body = ""
            rb = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema", {})
            if "$ref" in rb:
                body = rb["$ref"].rsplit("/", 1)[-1]
            elif rb:
                body = "JSON"
            summary = op.get("summary") or ""
            desc = (op.get("description") or "").strip().split("\n\n")[0].replace("\n", " ")
            by_tag.setdefault(tag, []).append([f"`{method.upper()}`", _code(path), _code(params), body,
                                               desc if desc and desc != summary else summary])
    for tag in sorted(by_tag):
        parts.append(f"## {tag}\n\n")
        parts.append(_table(["Method", "Path", "Query", "Body", "Description"], sorted(by_tag[tag], key=lambda r: (r[1], r[0]))) + "\n")
    return "".join(parts)


# ------------------------------------------------------------------------------------------ features
def features() -> str:
    spec = yaml.safe_load((REPO_ROOT / "contracts" / "features" / "feature_schema.yaml").read_text())
    parts = [HEADER.format(src="contracts/features/feature_schema.yaml"), "# Feature catalog\n\n",
             f"{len(spec['features'])} features, in model-tensor order (index = position in the tensor). Stream "
             "features are computed by the Flink job (or the gateway's inline path) with bucketed event-time "
             "windows; profile features are seeded into the online store from the synthetic world; derived "
             "features are computed at scoring time, by a library function (`fn`) or a CEL expression over `event` "
             "and `f` (`expr`, numbers or booleans as 1 / 0: new event-level features need no code). Semantics: see "
             "the header of the schema file and "
             "[contracts.md](../contracts.md).\n\n"]
    parts.append("## Entities\n\n" + _table(["Entity", "Key"], [[_code(k), _code(v["key"])] for k, v in spec["entities"].items()]) + "\n")
    parts.append("## Filters (CEL over `event`)\n\n" + _table(["Name", "Expression"], [[_code(k), _code(v)] for k, v in spec["filters"].items()]) + "\n")
    rows = []
    for i, f in enumerate(spec["features"]):
        if f["source"] == "stream":
            what = f["agg"] + (f"({f['value']})" if f.get("value") else "") + (f" where {f['filter']}" if f.get("filter") else "")
            win = f"{f['window']} / {f['granularity']}"
        elif f["source"] == "profile":
            what, win = f"profile.{f['field']}", ""
        else:
            what, win = (f"fn {f['fn']}()" if f.get("fn") else f"expr {f['expr']}"), ""
        rows.append([i, _code(f["name"]), f["source"], f.get("entity", ""), _code(what), win, f.get("default", 0)])
    parts.append("## Features\n\n" + _table(["#", "Name", "Source", "Entity", "Definition", "Window / bucket", "Default"], rows))
    return "".join(parts)


