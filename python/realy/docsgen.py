HEADER = "<!-- GENERATED by `python -m realy.docsgen` from {src} - do not edit by hand. -->\n\n"


def _cell(s: Any) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def _table(head: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def _code(s: Any) -> str:
    s = str(s)
    return f"`{s}`" if s else ""


# ------------------------------------------------------------------------------------------ scenario
SCENARIO_MODELS = ["Scenario", "WorldSpec", "TrafficSpec", "RateProfile", "FraudSpec", "CampaignSpec",
                   "SyncSpec", "BudgetSpec", "GuardrailSpec"]
SECTION_KEY = {"WorldSpec": "world", "TrafficSpec": "traffic", "RateProfile": "traffic.profile",
               "FraudSpec": "fraud", "CampaignSpec": "fraud.campaigns[]", "SyncSpec": "sync",
               "BudgetSpec": "budget", "GuardrailSpec": "guardrails"}


def _source_fields(cls: type) -> dict[str, tuple[str, str, str]]:
    """field -> (type text, default text, comment) straight from the class source."""
    out: dict[str, tuple[str, str, str]] = {}
    pending: list[str] = []
    for line in inspect.getsource(cls).splitlines()[1:]:
        if re.match(r"^    #\s?", line):
            pending.append(re.sub(r"^    #\s?", "", line))
            continue
        m = re.match(r"^    ([a-z_][a-z0-9_]*): (.+?)(?:\s+#\s*(.*))?$", line)
        if m and not line.strip().startswith(("def ", "@")):
            typ, _, default = m.group(2).partition(" = ")
            comment = " ".join(pending + ([m.group(3)] if m.group(3) else []))
            out[m.group(1)] = (typ.strip(), default.strip(), comment)
        pending = [] if not line.startswith("    #") else pending
    return out


def _default_text(field: Any, src_default: str) -> str:
    if field.default_factory is not None:
        try:
            v = field.default_factory()
        except TypeError:
            return ""
        if hasattr(v, "model_dump"):
            return "(object)"
        txt = json.dumps(v)
        return txt if len(txt) <= 90 else "see below"
    if src_default.startswith("Field("):
        return ""
    return src_default


def scenario_schema() -> str:
    parts = [HEADER.format(src="python/realy/scenario.py"), "# Scenario schema\n\n",
             "A scenario is one YAML file in `scenarios/` (or saved from the console's builder) that fully "
             "describes a reproducible run. Unknown keys are rejected. The JSON Schema is served at "
             "`GET /api/reference/scenario-schema`; the console builder validates against it.\n\n",
             "`scoring:` and `model_server:` are proto3-JSON documents of `ScoringConfig` / `ModelServerConfig` "
             "- see [config.md](config.md). Fields left out take the defaults listed there.\n\n"]
    for name in SCENARIO_MODELS:
        cls = getattr(scenario_mod, name)
        src = _source_fields(cls)
        key = SECTION_KEY.get(name, "(top level)")
        doc = (cls.__doc__ or "").strip()
        parts.append(f"## `{key}` - {name}\n\n")
        if doc and not doc.startswith(("Usage docs", "!!! abstract")):
            parts.append(doc + "\n\n")
        rows = []
        for fname, field in cls.model_fields.items():
            typ, sdef, comment = src.get(fname, ("", "", ""))
            rows.append([_code(fname), _code(typ), _code(_default_text(field, sdef)), comment])
        parts.append(_table(["Field", "Type", "Default", "Description"], rows) + "\n")
        if name == "FraudSpec":
            parts.append("Default `mix`: " + ", ".join(f"`{k}` {v:g}" for k, v in
                                                       cls.model_fields["mix"].default_factory().items()) + "\n\n")
    parts.append("## Fraud typologies\n\n`" + "`, `".join(scenario_mod.fraud_kinds()) + "` - described in "
                 "[synthetic-data.md](../synthetic-data.md).\n")
    return "".join(parts)


# ------------------------------------------------------------------------------------------ config
_FIELD = re.compile(r"^\s*(repeated\s+)?(map<[^>]+>|[\w.]+)\s+(\w+)\s*=\s*(\d+)\s*;\s*(?://\s*(.*))?$")
_ENUMV = re.compile(r"^\s*(\w+)\s*=\s*(\d+)\s*;\s*(?://\s*(.*))?$")


def _parse_proto(text: str) -> list[dict[str, Any]]:
    """Messages / enums of one .proto file with their leading and trailing `//` comments, in order.
    `// ---- title ----` lines become section headings. Handles one-line messages and oneofs."""
    blocks: list[dict[str, Any]] = []
    comments: list[str] = []
    cur: dict[str, Any] | None = None
    oneof: str | None = None

    def add_item(line: str) -> None:
        assert cur is not None
        m = _FIELD.match(line) if cur["kind"] == "message" else _ENUMV.match(line)
        if not m:
            return
        if cur["kind"] == "message":
            cur["items"].append({"name": m.group(3), "type": (m.group(1) or "") + m.group(2), "num": int(m.group(4)),
                                 "doc": " ".join(comments + ([m.group(5)] if m.group(5) else [])), "oneof": oneof})
        else:
            cur["items"].append({"name": m.group(1), "num": int(m.group(2)),
                                 "doc": " ".join(comments + ([m.group(3)] if m.group(3) else []))})

    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("//"):
            c = line[2:].strip()
            if c.startswith("----"):
                blocks.append({"kind": "section", "name": c.strip("- ").strip()})
                comments = []
            else:
                comments.append(c)
            continue
        if cur is None:
            m = re.match(r"^(message|enum)\s+(\w+)\s*\{(.*)$", line)
            if not m:
                comments = []          # file header, syntax/package/option lines
                continue
            cur = {"kind": m.group(1), "name": m.group(2), "doc": " ".join(comments), "items": []}
            comments = []
            rest = m.group(3).strip()
            if rest.endswith("}"):     # one-line message
                for part in filter(None, (x.strip() for x in rest[:-1].split(";"))):
                    add_item(part + ";")
                blocks.append(cur)
                cur = None
            continue
        if line.startswith("oneof "):
            oneof = re.match(r"oneof\s+(\w+)", line).group(1)
        elif line == "}":
            if oneof:
                oneof = None
            else:
                blocks.append(cur)
                cur = None
        elif line:
            add_item(line)
        comments = []
    return blocks


def config() -> str:
    path = REPO_ROOT / "contracts" / "proto" / "realy" / "bench" / "v1" / "control.proto"
    blocks = _parse_proto(path.read_text())
    defaults = {"ScoringConfig": SCORING_DEFAULTS, "ModelServerConfig": MODEL_SERVER_DEFAULTS}
    parts = [HEADER.format(src="contracts/proto/realy/bench/v1/control.proto"), "# Runtime configuration\n\n",
             "Runtime knobs of the Java services, as proto3 JSON (snake_case keys). The same document is used in "
             "a scenario's `scoring:` / `model_server:` sections, on the services' admin HTTP endpoints "
             "(`POST /admin/config`) and on the compacted `bench.control` topic, so changes made live from the "
             "console's control drawer use exactly this schema.\n\n",
             "Every run sends a complete config: fields a scenario leaves out are filled from the defaults below, "
             "so nothing leaks from one run into the next.\n\n"]
    for b in blocks:
        if b["kind"] == "section":
            parts.append(f"## {b['name'][:1].upper() + b['name'][1:]}\n\n")
            continue
        parts.append(f"### `{b['name']}`" + (" (enum)" if b["kind"] == "enum" else "") + "\n\n")
        if b["doc"]:
            parts.append(b["doc"] + "\n\n")
        if not b["items"]:
            continue
        if b["kind"] == "enum":
            parts.append(_table(["Value", "Number", "Meaning"], [[_code(i["name"]), i["num"], i["doc"]] for i in b["items"]]))
        else:
            d = defaults.get(b["name"])
            head = ["Field", "Type", "#"] + (["Default"] if d else []) + ["Description"]
            rows = []
            for i in b["items"]:
                typ = _code(i["type"]) + (f" (oneof {i['oneof']})" if i.get("oneof") else "")
                row = [_code(i["name"]), typ, i["num"]]
                if d:
                    row.append(_code(json.dumps(d[i["name"]])) if i["name"] in d else "")
                rows.append(row + [i["doc"]])
            parts.append(_table(head, rows))
        parts.append("\n")
    parts.append("## Example\n\n```yaml\nscoring:\n  budget_ms: 100\n  feature_deadline_ms: 30\n  model_deadline_ms: 80\n"
                 "  on_deadline: FALLBACK_RULES\n  feature_lookup_delay: { uniform: { min_ms: 2, max_ms: 8 } }\n"
                 "model_server:\n  service_time: { uniform: { min_ms: 30, max_ms: 100 } }\n  workers: 8\n"
                 "  max_batch: 16\n  max_queue_delay_us: 2000\n```\n")
    return "".join(parts)


# ------------------------------------------------------------------------------------------ CLI
def cli() -> str:
    import typer.main

    from .cli import app

    root = typer.main.get_command(app)
    parts = [HEADER.format(src="python/realy/cli.py"), "# CLI reference\n\n",
             "`pulsebench` drives everything the console does, from a shell or CI. In the Docker stack it is on the "
             "console container's PATH (`make console-shell`, or `docker compose exec console pulsebench ...`). "
             "`realy` is a legacy alias of the same command.\n\n"]

    def walk(cmd: Any, path: list[str]) -> None:
        if hasattr(cmd, "commands"):
            for name in sorted(cmd.commands):
                walk(cmd.commands[name], path + [name])
            return
        parts.append(f"## `pulsebench {' '.join(path)}`\n\n")
        if cmd.help:
            parts.append(inspect.cleandoc(cmd.help).split("\n\n")[0].replace("\n", " ") + "\n\n")
        args = [p for p in cmd.params if p.param_type_name == "argument"]
        opts = [p for p in cmd.params if p.param_type_name == "option" and p.name != "help"]
        ctx = cmd.context_class(cmd, info_name="pulsebench")

        def typ(p: Any) -> str:
            try:
                return str(p.display_type(ctx) or "").strip("<>")
            except Exception:  # noqa: BLE001
                return ""

        usage = "pulsebench " + " ".join(path) + "".join(f" {a.name.upper()}" for a in args) + (" [OPTIONS]" if opts else "")
        parts.append(f"```\n{usage}\n```\n\n")
        rows = []
        for a in args:
            rows.append([_code(a.name.upper()), "argument" + ("" if a.required else ", optional"), "", a.help or ""])
        for o in opts:
            flag = ", ".join(o.opts + o.secondary_opts)
            default = o.default
            if callable(default) or default in (None, (), [], False, ""):
                default = ""
            rows.append([_code(flag), "flag" if o.is_flag else typ(o).lower(), _code(default) if default != "" else "",
                         o.help or ""])
        if rows:
            parts.append(_table(["Parameter", "Type", "Default", "Description"], rows) + "\n")

    walk(root, [])
    return "".join(parts)


# ------------------------------------------------------------------------------------------ HTTP API
def http_api() -> str:
    from .control.app import app

    spec = app.openapi()
    parts = [HEADER.format(src="python/realy/control (FastAPI OpenAPI)"), "# Console HTTP API\n\n",
             "The console UI is a client of this API; scripts and CI can use it too. Live OpenAPI: "
             "`/api/openapi.json`, interactive explorer: `/api/swagger`.\n\n",
             "**Auth.** When `REALY_CONSOLE_TOKEN` is set every `/api/*` route except `/api/health` and "
             "`/api/auth/*` needs `Authorization: Bearer <token>` or the session cookie set by "
             "`POST /api/auth/login`. See [security.md](../security.md).\n\n",
             "**Live telemetry.** WebSocket `/api/live` (session cookie, Bearer header or `?token=`) pushes JSON "
             "messages: `status` (run queue + current run, on connect and on change), `metrics` (1 s "
             "`MetricsSnapshot` per source: emitter, collector, gateway, model, flink), `log` (driver log lines) "
             "and `decision` (a rate-limited sample of decisions, ~20/s, for the live feed). History for a "
             "late joiner: `GET /api/live/history`. Unauthorised connections are closed with code 4401.\n\n"]
    by_tag: dict[str, list[list[Any]]] = {}
    for path, ops in spec.get("paths", {}).items():
        for method, op in ops.items():
            tag = (op.get("tags") or ["console"])[0]
            params = ", ".join(("" if p.get("required") else "?") + p["name"] for p in op.get("parameters", [])
                               if p.get("in") == "query")
            body = ""
            rb = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema", {})
            if "$ref" in rb:
                body = rb["$ref"].rsplit("/", 1)[-1]
            elif rb:
                body = "JSON"
            summary = op.get("summary") or ""
            desc = (op.get("description") or "").strip().split("\n\n")[0].replace("\n", " ")
            by_tag.setdefault(tag, []).append([f"`{method.upper()}`", _code(path), _code(params), body,
                                               desc if desc and desc != summary else summary])
    for tag in sorted(by_tag):
        parts.append(f"## {tag}\n\n")
        parts.append(_table(["Method", "Path", "Query", "Body", "Description"], sorted(by_tag[tag], key=lambda r: (r[1], r[0]))) + "\n")
    return "".join(parts)


# ------------------------------------------------------------------------------------------ features
def features() -> str:
    spec = yaml.safe_load((REPO_ROOT / "contracts" / "features" / "feature_schema.yaml").read_text())
    parts = [HEADER.format(src="contracts/features/feature_schema.yaml"), "# Feature catalog\n\n",
             f"{len(spec['features'])} features, in model-tensor order (index = position in the tensor). Stream "
             "features are computed by the Flink job (or the gateway's inline path) with bucketed event-time "
             "windows; profile features are seeded into the online store from the synthetic world; derived "
             "features are computed at scoring time. Semantics: see the header of the schema file and "
             "[contracts.md](../contracts.md).\n\n"]
    parts.append("## Entities\n\n" + _table(["Entity", "Key"], [[_code(k), _code(v["key"])] for k, v in spec["entities"].items()]) + "\n")
    parts.append("## Filters (CEL over `event`)\n\n" + _table(["Name", "Expression"], [[_code(k), _code(v)] for k, v in spec["filters"].items()]) + "\n")
    rows = []
    for i, f in enumerate(spec["features"]):
        if f["source"] == "stream":
            what = f["agg"] + (f"({f['value']})" if f.get("value") else "") + (f" where {f['filter']}" if f.get("filter") else "")
            win = f"{f['window']} / {f['granularity']}"
        elif f["source"] == "profile":
            what, win = f"profile.{f['field']}", ""
        else:
            what, win = f"fn {f['fn']}()", ""
        rows.append([i, _code(f["name"]), f["source"], f.get("entity", ""), _code(what), win, f.get("default", 0)])
    parts.append("## Features\n\n" + _table(["#", "Name", "Source", "Entity", "Definition", "Window / bucket", "Default"], rows))
    return "".join(parts)


# ------------------------------------------------------------------------------------------ rules
def rules() -> str:
    parts = [HEADER.format(src="rules/*.yaml"), "# Rule catalog\n\n",
             "Rule sets are CEL over `f` (features, doubles) and `event` (transaction fields, enums by name). "
             "Evaluated by the Java scoring core and re-evaluated by `pulsebench verify` for parity. Precedence: "
             "DECLINE rule > ALLOW rule > score >= decline > REVIEW rule > score >= review > APPROVE.\n\n"]
    for p in sorted((REPO_ROOT / "rules").glob("*.yaml")):
        spec = yaml.safe_load(p.read_text())
        th = spec.get("thresholds", {})
        parts.append(f"## `{p.stem}` - version `{spec.get('version', '?')}`\n\n")
        parts.append(f"Model thresholds: review >= `{th.get('review')}`, decline >= `{th.get('decline')}`.\n\n")
        parts.append(_table(["Rule", "Action", "When", "Reason"],
                            [[_code(r["id"]), r["action"], _code(r["when"]), r.get("reason", "")] for r in spec["rules"]]) + "\n")
    return "".join(parts)


# ------------------------------------------------------------------------------------------ topics
def topics() -> str:
    spec = yaml.safe_load((REPO_ROOT / "contracts" / "kafka" / "topics.yaml").read_text())
    d = spec["defaults"]
    parts = [HEADER.format(src="contracts/kafka/topics.yaml"), "# Kafka topics\n\n",
             f"Production defaults: replication factor {d['replication_factor']}, min.insync.replicas "
             f"{d['min_insync_replicas']} (the single-broker compose and local Kubernetes stacks use 1). Partition "
             "counts target 10k TPS - see [capacity-planning.md](../capacity-planning.md).\n\n"]
    rows = []
    for name, t in spec["topics"].items():
        cfg = dict(t.get("config") or {})
        if "retention_ms" in t:
            h = int(t["retention_ms"]) / 3_600_000
            cfg["retention"] = f"{h:g}h" if h < 48 else f"{h / 24:g}d"
        rows.append([_code(name), t.get("partitions", ""), _code(t.get("key", "")), _code(t.get("value", "")),
                     t.get("timestamp", ""), ", ".join(f"{k}={v}" for k, v in cfg.items())])
    parts.append(_table(["Topic", "Partitions", "Key", "Value", "Timestamp", "Config"], rows))
    return "".join(parts)


# ------------------------------------------------------------------------------------------ scenarios
def scenarios() -> str:
    from .scenario import Scenario

    parts = [HEADER.format(src="scenarios/*.yaml"), "# Scenario catalog\n\n",
             "The bundled scenario packs. Run one from the console's **Launch** page, or "
             "`pulsebench run <name>`. Edit them in the **Scenarios** builder or as YAML "
             "([scenario-schema.md](scenario-schema.md)).\n\n"]
    rows = []
    for p in sorted((REPO_ROOT / "scenarios").glob("*.yaml")):
        sc = Scenario.model_validate(yaml.safe_load(p.read_text()))
        prof = sc.traffic.profile
        dur = sc.traffic.duration_s
        lo, hi = prof.rate_at(0.0), max(prof.rate_at(t * dur / 200) for t in range(200))
        load = f"{lo:,.0f} TPS" if prof.kind == "constant" else f"{prof.kind} {lo:,.0f} -> {hi:,.0f} TPS"
        camps = ", ".join(sorted({c.kind for c in sc.fraud.campaigns})) or "background mix"
        rows.append([_code(p.stem), sc.topology, load, f"{dur / 60:g} min" if dur >= 120 else f"{dur:g} s",
                     camps, f"{sc.budget.e2e_p99_ms:g} / {sc.budget.hot_path_p99_ms:g} ms",
                     (sc.description or "").strip().split("\n")[0]])
    parts.append(_table(["Scenario", "Topology", "Load", "Duration", "Fraud campaigns", "p99 budget (e2e / hot)", "Description"], rows))
    return "".join(parts)


PAGES = {"scenario-schema.md": scenario_schema, "config.md": config, "cli.md": cli, "http-api.md": http_api,
         "features.md": features, "rules.md": rules, "topics.md": topics, "scenarios.md": scenarios}


def write() -> list[Path]:
    OUT.mkdir(parents=True, exist_ok=True)
    out = []
    for name, fn in PAGES.items():
        p = OUT / name
        p.write_text(fn())
        out.append(p)
    return out


if __name__ == "__main__":
    for p in write():
        print(p)
